/**
 * Apply branding.json → package.json (electron-builder) + electron/branding.cjs
 *
 * Usage:  node scripts/apply-branding.mjs
 * Or:     npm run brand
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

const brandingPath = path.join(root, "branding.json");
if (!fs.existsSync(brandingPath)) {
  console.error("Missing branding.json in project root.");
  process.exit(1);
}

const b = JSON.parse(fs.readFileSync(brandingPath, "utf8"));
const appName = String(b.appName || "Bar POS").trim() || "Bar POS";
const shortName = String(b.shortName || appName).trim() || appName;
const description = String(b.description || "Bar point of sale").trim();
const author = String(b.author || "Bar POS").trim();
const appId = String(b.appId || "com.barpos.cloud").trim() || "com.barpos.cloud";
const iconFile = String(b.iconFile || "public/icon-512.png").trim();
const windowWidth = Number(b.windowWidth) || 1280;
const windowHeight = Number(b.windowHeight) || 800;

const iconAbs = path.join(root, iconFile);
if (!fs.existsSync(iconAbs)) {
  console.warn("Warning: icon not found at", iconFile);
  console.warn("Place a PNG (ideally 512×512) there, or change iconFile in branding.json");
}

// 1) package.json — electron-builder product name + icons
const pkgPath = path.join(root, "package.json");
const pkg = JSON.parse(fs.readFileSync(pkgPath, "utf8"));
pkg.description = description;
pkg.author = author;
pkg.build = pkg.build || {};
pkg.build.appId = appId;
pkg.build.productName = appName;
pkg.build.win = pkg.build.win || {};
pkg.build.win.icon = iconFile;
pkg.build.mac = pkg.build.mac || {};
pkg.build.mac.icon = iconFile;
pkg.build.linux = pkg.build.linux || {};
pkg.build.linux.icon = iconFile;
if (pkg.build.nsis) {
  pkg.build.nsis.shortcutName = shortName;
}
fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + "\n");
console.log("Updated package.json → productName:", appName);

// 2) electron/branding.cjs — read by main process at runtime
const brandOut = path.join(root, "electron", "branding.cjs");
const brandSrc = `/* Auto-generated by npm run brand — edit branding.json instead */
module.exports = ${JSON.stringify(
  {
    appName,
    shortName,
    description,
    author,
    appId,
    iconFile,
    windowWidth,
    windowHeight,
  },
  null,
  2,
)};
`;
fs.writeFileSync(brandOut, brandSrc);
console.log("Wrote electron/branding.cjs");

// 3) Optional: copy icon into public as app icon aliases
console.log("");
console.log("Branding applied.");
console.log("  Name:  ", appName);
console.log("  Icon:  ", iconFile);
console.log("  App ID:", appId);
console.log("");
console.log("Next: npm run desktop:build:win   (or :mac / :linux)");
